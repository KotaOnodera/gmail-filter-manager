'use strict';
const fs=require('node:fs'),path=require('node:path');
function build(root=path.resolve(__dirname,'..'),output=path.join(root,'dist','installer')){
  const read=p=>fs.readFileSync(path.join(root,p),'utf8');
  const files=['Core','Labels','Sync','Sheets','Gmail','Messages','Jobs','Logging','Runtime','Menu','Web'].map(name=>({name,type:'SERVER_JS',source:read('src/'+name+'.js')}));
  ['Index','Styles','Session','Client'].forEach(name=>files.push({name,type:'HTML',source:read(name+'.html')}));
  files.push({name:'appsscript',type:'JSON',source:read('appsscript.json')});
  const code='// Generated by npm run build. Edit installer/ and src/, then rebuild.\n'+read('src/Core.js')+'\n'+read('src/Labels.js')+'\n'+read('src/Sheets.js')+'\nvar GFMInstallPayload = '+JSON.stringify(files,null,2)+';\n'+read('installer/Installer.js');
  fs.mkdirSync(output,{recursive:true});
  fs.writeFileSync(path.join(output,'Code.js'),code);
  fs.writeFileSync(path.join(output,'appsscript.json'),read('installer/appsscript.json'));
  return {output,files:['Code.js','appsscript.json']};
}
if(require.main===module){const result=build();console.log('Built standalone installer: '+path.relative(process.cwd(),result.output)+' ('+result.files.join(', ')+')');}
module.exports={build};
